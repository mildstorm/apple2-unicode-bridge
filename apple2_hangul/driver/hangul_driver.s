/* HANGUL_DRIVER.S - Unified Apple II Hangul and Hanja Multilingual System */

    * = $4000

KSW_LO      = $38
KSW_HI      = $39
DOS_KSW_LO  = $AA55
DOS_KSW_HI  = $AA56
AMP_VECTOR  = $03F5

CHRGET      = $00B1
TXTPTR_LO   = $B8
TXTPTR_HI   = $B9

KBD         = $C000
KBDSTRB     = $C010
TXTCLR      = $C050
TXTSET      = $C051
MIXCLR      = $C052
MIXSET      = $C053
PAGE1       = $C054
HIRES       = $C057

ACIA_DATA   = $C0A8
ACIA_STAT   = $C0A9
ACIA_CMD    = $C0AA
ACIA_CTRL   = $C0AB

PTR_LO      = $06
PTR_HI      = $07
COL_OFFSET  = $08
START_Y     = $09
SRC_LO      = $0A
SRC_HI      = $0B

INIT
    LDA #$00
    STA ACIA_STAT
    LDA #$1E
    STA ACIA_CTRL
    LDA #$0B
    STA ACIA_CMD

    LDA #$00
    STA BUF_HEAD
    STA BUF_TAIL

    LDA #$4C
    STA AMP_VECTOR
    LDA #<AMPERSAND_HANDLER
    STA AMP_VECTOR+1
    LDA #>AMPERSAND_HANDLER
    STA AMP_VECTOR+2

    LDA #<MY_KEYIN
    STA KSW_LO
    STA DOS_KSW_LO
    LDA #>MY_KEYIN
    STA KSW_HI
    STA DOS_KSW_HI

    JSR CLEAR_HGR

    RTS

AMPERSAND_HANDLER
    CMP #'"'
    BEQ RUN_AMP_STRING

    JSR CHRGET
    CMP #'"'
    BEQ RUN_AMP_STRING

    JMP RUN_TERMINAL_MODE

RUN_AMP_STRING
    STA TXTCLR
    STA HIRES
    STA PAGE1
    STA MIXSET

    LDA #$87
    JSR SEND_BYTE

SEND_STR_LOOP
    INC TXTPTR_LO
    BNE FETCH_STR_CHAR
    INC TXTPTR_HI
FETCH_STR_CHAR
    LDY #$00
    LDA (TXTPTR_LO),Y
    BEQ SEND_STR_END
    CMP #'"'
    BEQ SEND_STR_END
    JSR SEND_BYTE
    JMP SEND_STR_LOOP

SEND_STR_END
    PHA
    LDA #$00
    JSR SEND_BYTE

    JSR PROCESS_PC_DRAWING

    PLA
    CMP #'"'
    BNE AMP_RTS
    JSR CHRGET

AMP_RTS
    RTS

PROCESS_PC_DRAWING
    JSR RECV_BYTE
    CMP #$00
    BEQ DRAWING_DONE
    CMP #$81
    BEQ EXEC_DRAW
    CMP #$82
    BEQ EXEC_CLEAR
    CMP #$84
    BEQ EXEC_SCROLL
    JMP PROCESS_PC_DRAWING

EXEC_DRAW
    JSR DRAW_ONE_GLYPH
    JMP PROCESS_PC_DRAWING

EXEC_CLEAR
    JSR CLEAR_HGR
    JMP PROCESS_PC_DRAWING

EXEC_SCROLL
    JSR SCROLL_HGR
    JMP PROCESS_PC_DRAWING

DRAWING_DONE
    RTS

MY_KEYIN
    LDA BUF_HEAD
    CMP BUF_TAIL
    BEQ READ_KBD

    STX SAVE_X
    LDX BUF_TAIL
    LDA BUF_START,X
    INC BUF_TAIL
    LDX SAVE_X
    ORA #$80
    RTS

READ_KBD
    LDA KBD
    BPL READ_KBD
    STA KBDSTRB
    AND #$7F

    CMP #$0B            ; Ctrl+K?
    BEQ HANDLE_CTRL_K

    CMP #$1B            ; ESC key?
    BNE NOT_ESC
    STA TXTSET          ; Switch to TEXT screen ($C051)!
    LDA #$8D            ; Return Carriage Return ($8D) to GETLN
    RTS

NOT_ESC
    CMP #'a'
    BCC NOT_LOWER
    CMP #'z'+1
    BCS NOT_LOWER
    SEC
    SBC #$20            ; Convert lowercase 'a'-'z' to uppercase 'A'-'Z'
NOT_LOWER
    ORA #$80
    RTS

HANDLE_CTRL_K
    STX SAVE_X
    STY SAVE_Y
    LDA #$0B
    JSR SEND_BYTE

WAIT_FOR_PC_INPUT
    LDA ACIA_STAT
    AND #$08
    BNE READ_INPUT_CMD

    LDA KBD
    BPL WAIT_FOR_PC_INPUT
    STA KBDSTRB
    AND #$7F
    CMP #$1B
    BEQ CANCEL_PC_INPUT
    JMP WAIT_FOR_PC_INPUT

READ_INPUT_CMD
    LDA ACIA_DATA
    CMP #$86
    BNE WAIT_FOR_PC_INPUT

    JSR RECV_BYTE
    TAX
    BEQ INPUT_EMPTY

    LDY #$00
INPUT_LOOP
    JSR RECV_BYTE
    STA BUF_START,Y
    INY
    DEX
    BNE INPUT_LOOP

    STY BUF_HEAD
    LDA #$00
    STA BUF_TAIL

    LDX SAVE_X
    LDY SAVE_Y
    JMP MY_KEYIN

INPUT_EMPTY
    LDX SAVE_X
    LDY SAVE_Y
    JMP READ_KBD

CANCEL_PC_INPUT
    STA TXTSET
    LDX SAVE_X
    LDY SAVE_Y
    LDA #$8D
    RTS

RUN_TERMINAL_MODE
    STA TXTCLR
    STA HIRES
    STA PAGE1
    STA MIXCLR

    JSR CLEAR_HGR

    LDA #$AA
    JSR SEND_BYTE

TERM_LOOP
    LDA KBD
    BPL CHECK_TERM_SERIAL
    STA KBDSTRB
    AND #$7F
    CMP #$1B
    BEQ EXIT_TERM
    JSR SEND_BYTE

CHECK_TERM_SERIAL
    LDA ACIA_STAT
    AND #$08
    BEQ TERM_LOOP

    LDA ACIA_DATA
    CMP #$81
    BEQ TERM_DO_DRAW
    CMP #$82
    BEQ TERM_DO_CLEAR
    CMP #$83
    BEQ EXIT_TERM
    CMP #$84
    BEQ TERM_DO_SCROLL
    JMP TERM_LOOP

TERM_DO_DRAW
    JSR DRAW_ONE_GLYPH
    JMP TERM_LOOP

TERM_DO_CLEAR
    JSR CLEAR_HGR
    JMP TERM_LOOP

TERM_DO_SCROLL
    JSR SCROLL_HGR
    JMP TERM_LOOP

EXIT_TERM
    STA TXTSET
    RTS

DRAW_ONE_GLYPH
    JSR RECV_BYTE
    ASL
    STA COL_OFFSET

    JSR RECV_BYTE
    ASL
    ASL
    ASL
    ASL
    STA START_Y

    LDX #$00
GLYPH_ROW_LOOP
    TXA
    CLC
    ADC START_Y
    TAY
    LDA HGR_LO,Y
    CLC
    ADC COL_OFFSET
    STA PTR_LO
    LDA HGR_HI,Y
    ADC #$00
    STA PTR_HI

    JSR RECV_BYTE
    LDY #$00
    STA (PTR_LO),Y

    JSR RECV_BYTE
    INY
    STA (PTR_LO),Y

    INX
    CPX #16
    BNE GLYPH_ROW_LOOP
    RTS

CLEAR_HGR
    LDA #$20
    STA PTR_HI
    LDA #$00
    STA PTR_LO
    TAY
    LDA #$00
CLR_LOOP
    STA (PTR_LO),Y
    INY
    BNE CLR_LOOP
    INC PTR_HI
    LDX PTR_HI
    CPX #$40
    BNE CLR_LOOP
    RTS

SCROLL_HGR
    LDX #$00
SCROLL_LINE
    TXA
    CLC
    ADC #16
    TAY
    LDA HGR_LO,Y
    STA SRC_LO
    LDA HGR_HI,Y
    STA SRC_HI

    LDA HGR_LO,X
    STA PTR_LO
    LDA HGR_HI,X
    STA PTR_HI

    LDY #39
COPY_40
    LDA (SRC_LO),Y
    STA (PTR_LO),Y
    DEY
    BPL COPY_40

    INX
    CPX #176
    BNE SCROLL_LINE

    LDA #0
CLEAR_BOTTOM
    LDA HGR_LO,X
    STA PTR_LO
    LDA HGR_HI,X
    STA PTR_HI
    LDY #39
CLR_40
    STA (PTR_LO),Y
    DEY
    BPL CLR_40
    INX
    CPX #192
    BNE CLEAR_BOTTOM
    RTS

SEND_BYTE
    PHA
WAIT_TX
    LDA ACIA_STAT
    AND #$10
    BEQ WAIT_TX
    PLA
    STA ACIA_DATA
    RTS

RECV_BYTE
    LDA ACIA_STAT
    AND #$08
    BEQ RECV_BYTE
    LDA ACIA_DATA
    RTS

SAVE_X     .byte 0
SAVE_Y     .byte 0
BUF_HEAD   .byte 0
BUF_TAIL   .byte 0
BUF_START  .dsb 256, 0

HGR_LO
#include "hgr_lo.inc"

HGR_HI
#include "hgr_hi.inc"
