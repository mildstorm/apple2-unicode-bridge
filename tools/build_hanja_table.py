#!/usr/bin/env python3
"""Builds hanja_table.txt, the Hangul reading -> Hanja candidates table used
by the Ctrl+K Hanja conversion, from the Unicode Han Database (Unihan).

    python tools/build_hanja_table.py path/to/Unihan_Readings.txt path/to/Unihan_IRGSources.txt

Unihan.zip: https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip

Readings come from kHangul ("한:0E"; source letters: E = the 1,800 basic
education Hanja, 0 = KS X 1001, N = name Hanja). Candidates for a reading
are ordered: basic education Hanja first, then KS X 1001, then the rest;
within each group by how often the character is used (kHanyuPinlu counts,
the only frequency data Unihan has), then by stroke count.
"""
import os
import re
import sys
import unicodedata
from collections import defaultdict

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "hanja_table.txt")


def read_fields(path, wanted):
    data = defaultdict(dict)
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            cp, field, value = line.rstrip("\n").split("\t", 2)
            if field in wanted:
                data[int(cp[2:], 16)][field] = value
    return data


def main(readings_path, irg_path):
    data = read_fields(readings_path, {"kHangul", "kHanyuPinlu"})
    for cp, fields in read_fields(irg_path, {"kTotalStrokes"}).items():
        data[cp].update(fields)

    table = defaultdict(set)
    for cp, fields in data.items():
        if "kHangul" not in fields:
            continue
        freq = sum(int(n) for n in re.findall(r"\((\d+)\)", fields.get("kHanyuPinlu", "")))
        strokes = int(fields.get("kTotalStrokes", "99").split()[0])
        for entry in fields["kHangul"].split():
            reading, _, src = entry.partition(":")
            group = 0 if "E" in src else 1 if "0" in src else 2
            table[reading].add((group, -freq, strokes, cp))

    for reading, entries in table.items():
        # A character listed twice for one reading keeps its best group
        # and a compatibility ideograph (U+F900..) whose unified form is
        # already a candidate is dropped, as the two look the same
        best = {}
        for e in sorted(entries):
            best.setdefault(e[3], e)
        table[reading] = {e for cp, e in best.items()
                          if not (0xF900 <= cp <= 0xFAFF
                                  and ord(unicodedata.normalize("NFC", chr(cp))) in best)}

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Hangul reading<TAB>Hanja candidates, most common first.\n")
        f.write("# Generated by tools/build_hanja_table.py from the Unicode Han Database\n")
        f.write("# (Unihan, kHangul / kHanyuPinlu / kTotalStrokes), Unicode License v3.\n")
        for reading in sorted(table):
            f.write(reading + "\t" + "".join(chr(c[3]) for c in sorted(table[reading])) + "\n")
    print(f"{OUT}: {len(table)} readings, {sum(len(v) for v in table.values())} entries")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
